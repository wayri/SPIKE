import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import ts from "typescript";
const load = async name => {
  const js = ts.transpileModule(readFileSync(new URL(`../src/${name}.ts`, import.meta.url), "utf8"), { compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 } }).outputText;
  return import(`data:text/javascript;base64,${Buffer.from(js).toString("base64")}`);
};
const { copyPlotData, pastePlotTraces, isCartesianPlot, MAX_PLOT_CLIPBOARD_BYTES } = await load("plotClipboard");
const { zoomPlotRange, panPlotRange, wheelPlotFactor } = await load("plotInteraction");
const { preparePlotLayout } = await load("plotLayout");
const axesJs = ts.transpileModule(readFileSync(new URL("../src/plotAxisSettings.ts", import.meta.url), "utf8"), { compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 } }).outputText;
const { buildPlotAxes } = await import(`data:text/javascript;base64,${Buffer.from(axesJs).toString("base64")}`);
const layout = { xaxis: { title: { text: "Time (ns)" } }, yaxis: { title: "Voltage (V)" } };
const prepared = preparePlotLayout(layout);
assert.equal(prepared.yaxis.title.text, "Voltage (V)"); assert.equal(prepared.yaxis.title.standoff, 10);
assert.equal(prepared.xaxis.automargin, true); assert.equal(layout.yaxis.title, "Voltage (V)");
assert.equal(preparePlotLayout({ scene: { zaxis: { title: "Z (mm)" } } }).scene.zaxis.title.text, "Z (mm)");
assert.equal(prepared.xaxis.showline, true); assert.equal(prepared.xaxis.ticks, "outside");
assert.equal(prepared.legend.maxheight, .2, "long legends cannot consume the graph");
assert.equal(preparePlotLayout({ paper_bgcolor: "black" }, { text: "black", line: "gray", grid: "gray", surface: "white" }).paper_bgcolor, "white", "chart surface follows its control theme");
const draft = { x: { scale: "log", auto: false, minimum: "1", maximum: "1000" }, y: { scale: "linear", auto: true, minimum: "", maximum: "" }, grid: "minor", crosshair: true };
const axisOptions = buildPlotAxes(draft, [{ x: [1, 10], y: [0, 1] }]);
assert.deepEqual(axisOptions.xaxis.range, [0, 3]); assert.equal(axisOptions.xaxis.minor.showgrid, true);
assert.equal(axisOptions.yaxis.autorange, true); assert.equal(axisOptions.xaxis.showspikes, true);
assert.throws(() => buildPlotAxes(draft, [{ x: [0, 10], y: [0, 1] }]), /positive coordinates/);
assert.throws(() => buildPlotAxes({ ...draft, x: { ...draft.x, minimum: "0" } }, []), /log bounds/);
assert.throws(() => buildPlotAxes({ ...draft, x: { ...draft.x, maximum: "1" } }, []), /minimum smaller/);
assert.throws(() => buildPlotAxes({ ...draft, x: { ...draft.x, maximum: "Infinity" } }, []), /finite/);
const data = [{ type: "scatter", name: "Board A", x: [0, 1, 3], y: [1, null, 2], customdata: ["source", "gap", "source"] },
  { type: "scatter", name: "Board B", x: new Float64Array([.2, 2]), y: [3, 4] }];
const before = JSON.stringify(data);
const text = copyPlotData(data, layout, "Fixture");
assert.ok(text.startsWith("Series\tTime (ns)\tVoltage (V)"), "spreadsheet data includes axis labels and units");
const imported = pastePlotTraces(text, layout);
assert.equal(imported.length, 2);
assert.deepEqual(imported[0].x, [0, 1, 3]); assert.deepEqual(imported[0].y, [1, null, 2]);
assert.equal(imported[0].connectgaps, false); assert.equal(imported[0].meta.importedComparison, true);
assert.equal(JSON.stringify(data), before, "clipboard serialization cannot mutate solver-owned data");
assert.deepEqual(pastePlotTraces("0\t1\n2\t3", layout)[0].y, [1, 3]);
assert.deepEqual(pastePlotTraces("0\t1\n\t\n2\t3", layout)[0].y, [1, null, 3], "fully blank tab-separated row remains a line break");
assert.throws(() => pastePlotTraces("Time (ms)\tVoltage (V)\n0\t1", layout), /unit ms differs/);
assert.throws(() => pastePlotTraces("0\tInfinity\n1\t2", layout), /finite/);
assert.throws(() => pastePlotTraces("NaN\tInfinity\n1\t2", layout), /finite/);
assert.deepEqual(pastePlotTraces(copyPlotData([{ x: [0, 1], y: [2, null] }], layout, "gap"), layout)[0].y, [2, null], "trailing blank sample remains a gap");
assert.throws(() => copyPlotData([{ x: Array(50001).fill(1), y: Array(50001).fill(1) }], {}, "large"), /Too many/);
assert.ok(copyPlotData([{ name: "=SUM(A1)", x: [0], y: [1] }], {}, "formula").includes("'="), "spreadsheet labels cannot become formulas");
assert.throws(() => pastePlotTraces("0\t1\t2\t3", layout), /two columns/);
assert.throws(() => pastePlotTraces("X\tY", layout), /between 1 and 24/);
assert.throws(() => pastePlotTraces(" ", layout), /samples|finite/);
assert.throws(() => pastePlotTraces("x".repeat(MAX_PLOT_CLIPBOARD_BYTES + 1), layout), /2 MB/);
assert.throws(() => pastePlotTraces('{"contract":"spike/plot-clipboard/v1","traces":[{"x":[0],"y":[1,2]}]}', layout), /equal lengths/);
assert.throws(() => pastePlotTraces("{invalid", layout), /malformed/);
assert.throws(() => pastePlotTraces("0\t1\n1\t2", { xaxis: { type: "log" } }), /positive/);
const hostile = pastePlotTraces("Series\tX\tY\n<img src=x onerror=alert(1)>Signal\t0\t1", {});
assert.equal(hostile[0].name, "Clipboard: Signal");
const spatial = [{ type: "scatter3d", x: [0, 1], y: [0, 1], z: [0, 2] }];
const packet = copyPlotData(spatial, {}, "3D"); assert.equal(JSON.parse(packet).traces[0].z[1], 2);
const surface = [{ type: "surface", x: [[0, 1]], y: [[0, 0]], z: [[1, null]], surfacecolor: [[-10, -20]], colorbar: { title: "Relative dB" } }];
const surfacePacket = JSON.parse(copyPlotData(surface, {}, "surface"));
assert.deepEqual(surfacePacket.traces[0].x, [[0, 1]]); assert.deepEqual(surfacePacket.traces[0].surfacecolor, [[-10, -20]]); assert.equal(surfacePacket.traces[0].valueLabel, "Relative dB");
assert.throws(() => pastePlotTraces(packet, {}), /2D/);
assert.equal(isCartesianPlot(spatial), false); assert.equal(isCartesianPlot(data), true);
assert.deepEqual(zoomPlotRange([0, 10], .5, .2), [1, 6]);
assert.equal((zoomPlotRange([0, 10], .5, .2)[1] - zoomPlotRange([0, 10], .5, .2)[0]) * .2 + 1, 2, "zoom retains the pointer anchor");
assert.deepEqual(zoomPlotRange([4, 6], .5), [4.5, 5.5], "log axes zoom in exponent space without changing data");
assert.deepEqual(panPlotRange([10, -10], .1), [8, -12], "reversed axes preserve direction");
assert.throws(() => zoomPlotRange([0, 10], 0), /Invalid/);
assert.ok(wheelPlotFactor(-100, 0) < 1); assert.ok(wheelPlotFactor(100, 0) > 1);
assert.equal(wheelPlotFactor(1, 1), wheelPlotFactor(16, 0), "line and pixel wheel deltas normalize consistently");
console.log("Plot clipboard roundtrip, units, gaps, bounds, typed arrays, malformed input and anchored zoom/pan checks passed.");
