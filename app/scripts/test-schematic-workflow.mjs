import assert from "node:assert/strict";
import { importTestTypescript } from "./import-test-typescript.mjs";
const { generateTopology, appendTopology } = await importTestTypescript("topologyGeneration");
const { layoutTopology, validateTopologyPorts, calculatePowerTree } = await importTestTypescript("powerTree");
const { schematicHeight, schematicPort, schematicWire } = await importTestTypescript("schematicGeometry");
const { thermalSchematic, emiSchematic } = await importTestTypescript("workflowSchematics");
const inputs = { source: "Supply", net: "+12V", sinks: "Controller\nSensor", voltage: "12", current: "0.25", sourcePad: "", sinkPad: "" };
const power = generateTopology("pi", inputs, null);
assert.equal(power.nodes.length, 4);
assert.equal(calculatePowerTree(power).loadPowerW, 6);
assert.equal(validateTopologyPorts(power).filter(issue => issue.severity === "error").length, 0);
assert.ok(power.nodes.flatMap(node => node.ports).filter(port => port.kind === "return").every(port => !port.net));
for (const voltage of ["", "-1", "0", "Infinity", "NaN"]) assert.throws(() => generateTopology("pi", { ...inputs, voltage }, null));
assert.throws(() => generateTopology("pi", { ...inputs, sinks: "U1,U1" }, null));
const signal = generateTopology("si", { ...inputs, net: "CLK" }, null);
assert.equal(validateTopologyPorts(signal).filter(issue => issue.severity === "error").length, 0, "SI branches must use distinct limited output ports");
const appended = appendTopology(power, power);
assert.equal(new Set(appended.nodes.map(node => node.id)).size, 8);
assert.equal(new Set(appended.edges.map(edge => edge.id)).size, 6);
assert.ok(appended.nodes.slice(4).every(node => node.y > Math.max(...power.nodes.map(node => node.y))));
assert.equal(power.nodes.length, 4, "Appending must not mutate the source sheet");
const chain = Array.from({ length: 14 }, (_, index) => ({ id: `n${index}`, kind: "channel", label: `N${index}`, x: 0, y: 0, origin: "user" }));
const edges = chain.slice(1).map((node, index) => ({ id: `e${index}`, from: chain[index].id, to: node.id, kind: "signal", origin: "user" }));
const laidOut = layoutTopology(chain, [...edges].reverse());
assert.ok(laidOut.every((node, i) => !i || node.x > laidOut[i - 1].x), "Deep paths cannot collapse into the last rank");
const cyclic = layoutTopology(chain, [...edges, { ...edges[0], from: "n13", to: "n0" }]);
assert.ok(cyclic.every(node => Number.isFinite(node.x) && Number.isFinite(node.y)));
const load = power.nodes.find(node => node.kind === "load");
const point = schematicPort(load, "pi", "in", "left");
assert.equal(point.y, load.y + schematicHeight(load, "pi") / 3);
const feedback = schematicWire({ from: power.nodes[3].id, to: power.nodes[0].id }, power.nodes, "pi");
assert.ok(feedback.d.includes(" V ") && !feedback.d.includes(" C "));
const board = { pads: [{ id: "a", ref: "U1", name: "1", net: "CLK" }, { id: "b", ref: "U2", name: "1", net: "CLK" }] };
const boardSignal = generateTopology("si", { ...inputs, sourcePad: "a", sinkPad: "b" }, board);
assert.equal(boardSignal.nodes[0].terminalPadId, "a");
assert.ok(boardSignal.nodes[0].ports.filter(port => port.kind === "reference").every(port => !port.padIds));
assert.throws(() => generateTopology("si", { ...inputs, sourcePad: "a", sinkPad: "b" }, { pads: [board.pads[0], { ...board.pads[1], net: "DATA" }] }));
const thermal = thermalSchematic({ ambient_temperature_c: 25, heat_sources: [{ id: "board", power_w: 5, theta_ja_c_per_w: 10 }, { element_id: "off", id: "off-source", power_w: 3 }], thermal_elements: [{ id: "off", enabled: false }], thermal_links: [{ id: "bad", from_id: "board", to_id: "off" }] });
assert.equal(thermal.edges.length, 1);
assert.ok(!thermal.nodes.some(node => node.id === "off-source"));
assert.ok(thermal.notes.some(note => note.includes("disabled endpoint")));
const emi = emiSchematic({ selected_nets: ["CLK"], return_nets: ["GND"], requested_analyses: ["near_field"], environment: { kind: "free_space" }, excitation: { mode: "prepass_results", ports: [] } });
assert.equal(emi.edges.length, 2);
assert.ok(emi.edges.every(edge => edge.scope));
assert.ok(emi.nodes.some(node => node.label === "GND"));
console.log("Schematic generation, deep/cyclic layout, fanout, append, port geometry, thermal links, and EMI scope passed");
