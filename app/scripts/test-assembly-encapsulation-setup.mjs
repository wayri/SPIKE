import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import ts from 'typescript';
import React from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
const require = createRequire(import.meta.url);
const source = readFileSync(new URL('../src/AssemblyEncapsulationSetup.tsx', import.meta.url), 'utf8');
const compiled = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020, jsx: ts.JsxEmit.ReactJSX } }).outputText;
const module = { exports: {} };
new Function('require', 'module', 'exports', compiled)(require, module, module.exports);
const { compileEncapsulation, default: Setup } = module.exports;
const base = { id: 'resin', kind: 'coating', bodies: ['board-A'], thickness: '.2', conductivity: '.5', provenance: 'Reviewed resin datasheet', bounds: '' };
assert.equal(compileEncapsulation([base]).valid, true);
assert.equal(compileEncapsulation([{ ...base, bodies: [] }]).valid, false);
assert.equal(compileEncapsulation([{ ...base, thickness: '' }]).valid, false);
assert.equal(compileEncapsulation([{ ...base, conductivity: 'NaN' }]).valid, false);
assert.equal(compileEncapsulation([{ ...base, provenance: '' }]).valid, false);
const potting = compileEncapsulation([{ ...base, kind: 'potting', bounds: '-2,-3,0,2,3,4' }]);
assert.equal(potting.valid, true);
assert.deepEqual(potting.recipes[0].fill_region.outer_mm, [[-2,-3],[2,-3],[2,3],[-2,3]]);
assert.equal(compileEncapsulation([{ ...base, kind: 'potting', bounds: '0 0 0 0 3 4' }]).valid, false);
const html = renderToStaticMarkup(React.createElement(Setup, { bodies: [], disabled: true, onChange() {} }));
assert.match(html, /box-shaped bodies/);
assert.match(html, /fieldset disabled/);
assert.match(html, /Add coating/);
assert.match(html, /Add potting/);
console.log('encapsulation material, dimensions, selection and disabled-state checks passed');
