import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import ts from 'typescript';
const path = new URL('../src/traceResultPlots.ts', import.meta.url);
const js = ts.transpileModule(readFileSync(path, 'utf8'), {compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}}).outputText
  .replace(/from "(\.\/[^"\n]+)"/g, (_, name) => `from "${new URL(name + '.ts', path)}"`);
const { buildTracePlot, resultTraceGroups, resultPlotFields, buildImpedancePlot } = await import(`data:text/javascript;base64,${Buffer.from(js).toString('base64')}`);
const face = (id,net,layer,x,value) => ({x_mm:x+.5,y_mm:.5,z_mm:0,element_id:id,net,layer,value,vertices_mm:[[x,0,0],[x+1,0,0],[x+1,1,0],[x,1,0]]});
const samples = [face('a','3V3','F.Cu',0,.01),face('b','3V3','F.Cu',1,.02),face('a','1V8','F.Cu',0,.8),face('a','3V3','B.Cu',0,.1)];
const before = JSON.stringify(samples);
const groups=resultTraceGroups(samples);
assert.equal(groups.length,4,'same element on different net/layer must not collide');
const spatial=buildTracePlot(samples,{net:'3V3',mode:'spatial',label:'Drop',unit:'mV',scale:1000});
assert.equal(spatial.shown,3); assert.equal(spatial.data[0].type,'mesh3d');
assert.equal(spatial.data[0].opacity,1); assert.equal(spatial.data[0].i.length,6);
assert.ok(spatial.data[0].intensity.every(value=>value<=100));
assert.equal(spatial.data[0].intensity[1],15,'shared same-layer vertex reconstructs a continuous display');
assert.equal(spatial.data[0].intensity[8],100,'back copper stays independent');
assert.equal(spatial.data[0].customdata[1][2],10,'hover returns source face sample, not display interpolation');
const height=buildTracePlot(samples,{net:'3V3',mode:'height',label:'Drop',unit:'mV',scale:1000});
assert.deepEqual(height.data[0].z,height.data[0].intensity,'height axis represents the displayed quantity with its unit conversion');
assert.match(height.layout.scene.zaxis.title.text,/mV/);
const single=buildTracePlot(samples,{net:'3V3',groupIds:[groups[0].id],mode:'samples',label:'Drop',unit:'mV',scale:1000});
assert.equal(single.shown,1); assert.deepEqual(single.data[0].y,[10]);
assert.equal(single.data[0].mode,'markers','source order must not imply a connected spatial path');
const compare=buildTracePlot(samples,{net:'3V3',groupIds:[groups[0].id,groups[1].id],mode:'samples',label:'Drop',unit:'mV'});
assert.equal(compare.data.length,2);
assert.equal(JSON.stringify(samples),before,'graph reconstruction cannot mutate solver data');
const points=Array.from({length:100001},(_,i)=>({x_mm:i,y_mm:0,value:i===12345?-999:i===76543?999:0,net:'P'}));
const bounded=buildTracePlot(points,{net:'P',mode:'samples',label:'V',unit:'V',maxSamples:100});
assert.equal(bounded.total,100001); assert.ok(bounded.shown<=100);
assert.ok(bounded.data[0].y.includes(-999)&&bounded.data[0].y.includes(999),'decimation retains extrema');
const invalid=buildTracePlot([{...samples[0],vertices_mm:[[NaN,0,0]]},{x_mm:NaN,y_mm:0,value:1,net:'3V3'}],{net:'3V3',mode:'spatial',label:'V',unit:'V'});
assert.equal(invalid.shown,1);assert.equal(invalid.data[0].type,'scatter3d','invalid face geometry remains a source marker');
const groupedResult={scalar_fields:{voltage_drop_v:[samples[0],samples[1]]},mesh:[{id:'a',source_id:'track-1',net:'3V3',layer:'F.Cu'},{id:'b',source_id:'track-1',net:'3V3',layer:'F.Cu'}],parasitics:[]};
assert.equal(resultTraceGroups(resultPlotFields(groupedResult,'pi')[0].samples).length,1,'exact mesh source IDs recover per-trace groups');
assert.deepEqual(resultPlotFields(groupedResult,'si'),[],'SI must not display PI-only quantities');
const networks=[{net:'SIG',impedance:[{frequency_hz:1e6,magnitude_ohm:50,phase_deg:0},{frequency_hz:1e3,magnitude_ohm:49,phase_deg:1}]}];
const ac=buildImpedancePlot(networks,'SIG'); assert.deepEqual(ac.data[0].x,[1e3,1e6]);assert.equal(ac.layout.xaxis.type,'log');
assert.equal(networks[0].impedance[0].frequency_hz,1e6,'sorting preserves solver source');
assert.equal(resultPlotFields({...groupedResult,parasitics:networks},'si')[0].key,'impedance_sweep');
console.log('Trace plots: net/layer/source ownership, exact hover, face continuity, bounded display, SI units and source immutability passed.');
