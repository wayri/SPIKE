import assert from 'node:assert/strict';
import { build } from 'esbuild';
import { readFile } from 'node:fs/promises';
const b=await build({entryPoints:['src/emViewportResults.ts'],bundle:true,platform:'node',format:'esm',write:false});
const api=await import(`data:text/javascript;base64,${Buffer.from(b.outputFiles[0].text).toString('base64')}`);
const coords=Array.from({length:9},(_,i)=>[i%3,Math.floor(i/3),5]);
const f=(x,y,z)=>Array.from({length:9},()=>[[x,0],[y,0],[z,0]]);
const plane={frequency_hz:1e9,grid_shape:[3,3],coordinates_mm:coords,valid:Array(9).fill(true),e_v_m:f(2,0,0),h_a_m:f(0,3,0)};
plane.valid[4]=false;plane.e_v_m[4]=null;plane.h_a_m[4]=null;
const record={id:'plane',label:'plane',result:{status:'completed',fields:{nearfield:{contract:'spike/emerge-nearfield-plane/v1',frequencies_hz:[1e9],planes:[plane]}}}};
const s={...api.defaultEMViewportSettings,quantity:'poynting'};
let d=api.buildEMViewportData(record,s);
assert.equal(d.values[0],3);assert.equal(d.values[4],null);assert.deepEqual(d.directions[0],[0,0,3]);assert.ok(!d.indices.includes(4));assert.deepEqual(d.positionsMm[0],[0,0,5]);
d=api.buildEMViewportData(record,{...s,quantity:'near_e',component:'x',projection:'instantaneous',phaseDeg:90});
assert.ok(Math.abs(d.values[0])<1e-12);assert.ok(d.highlights.every(v=>v===null));
assert.equal(api.buildEMViewportData(record,{...s,quantity:'near_e',projection:'phase'}),null);assert.equal(api.buildEMViewportData(record,{...s,frequencyIndex:9}),null);
const result=JSON.parse(await readFile('../examples/optycal/admitted_result.json','utf8')),actual={id:'actual',label:'actual',result};
const bare=api.buildEMViewportData(actual,{...s,quantity:'bare_e'}),total=api.buildEMViewportData(actual,{...s,quantity:'installed_e'});
assert.equal(bare.domain,'angular');assert.equal(bare.values.length,169);
const norm=v=>Math.hypot(...v.flat()),peak=Math.max(...result.fields.comparison.direct_e_xyz.map(norm));
for(let i=0;i<total.values.length;i++)assert.ok(Math.abs(Math.hypot(...total.positionsMm[i])/s.displayRadiusMm-Math.max(.02,norm(result.fields.comparison.total_e_xyz[i])/peak))<1e-10);
assert.equal(api.emViewportPayload({em_fields:result.fields}).fields,result.fields);
const normalizedBundle=await build({entryPoints:['src/analysisResults.ts'],bundle:true,platform:'node',format:'esm',write:false});
const normalizedApi=await import(`data:text/javascript;base64,${Buffer.from(normalizedBundle.outputFiles[0].text).toString('base64')}`);
const normalized=normalizedApi.normalizeSolverResult(result);
assert.deepEqual(normalized.em_fields,result.fields);
assert.equal(api.buildEMViewportData({id:'restored',label:'restored',result:normalized},{...s,quantity:'installed_e'}).values.length,169);
assert.deepEqual(normalizedApi.normalizeSolverResult(JSON.parse(JSON.stringify(normalized))).em_fields,result.fields);
const esp32 = JSON.parse(await readFile('../examples/esp32/evidence/rf_surrogate_rerun_result.json', 'utf8'));
const esp32Display = api.buildEMViewportData({ id: 'esp32', label: 'ESP32 surrogate', result: esp32 }, api.defaultEMViewportSettings);
assert.equal(esp32Display.domain, 'angular');
assert.equal(esp32Display.angularNeedsBoardAnchor, true, 'saved ESP32 angular samples have no PCB-frame origin and must be anchored for display');
assert.equal(bare.angularNeedsBoardAnchor, false, 'explicit antenna translation remains authoritative');
console.log('EM viewport coordinates, invalid holes, Poynting, phase and common-reference actual-data checks passed.');
