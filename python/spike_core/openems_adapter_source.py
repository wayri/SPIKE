def pad_polygon(pad):
    if pad.get("shape", "circle") != "rect" or pad.get("custom_geometry"):
        raise ValueError("GEOMETRY_PAD_CONTOUR_UNQUALIFIED")
    if any(pad.get(key) for key in ("drill", "drill_size_mm", "drill_shape", "plated")):
        raise ValueError("GEOMETRY_PADSTACK_UNMODELED")
    def numeric(value):
        try:
            return not isinstance(value, bool) and isinstance(value, (int, float)) and math.isfinite(value)
        except OverflowError:
            return False
    rotation = pad.get("rotation", pad.get("angle", 0))
    if not numeric(rotation):
        raise ValueError("GEOMETRY_PAD_ROTATION_INVALID")
    center, size = pad.get("at"), pad.get("size")
    if isinstance(center, dict) and set(center) == {"x", "y"}:
        center = [center["x"], center["y"]]
    if (not isinstance(center, (list, tuple)) or len(center) != 2
            or not isinstance(size, (list, tuple)) or len(size) != 2
            or not all(numeric(value) for value in list(center) + list(size))
            or min(size) <= 0):
        raise ValueError("GEOMETRY_PAD_DIMENSIONS_INVALID")
    angle = math.radians(rotation % 360)
    cosine, sine = math.cos(angle), math.sin(angle)
    points = [(center[0] + cosine * dx - sine * dy,
               center[1] + sine * dx + cosine * dy)
              for dx, dy in ((-size[0]/2, -size[1]/2), (size[0]/2, -size[1]/2),
                             (size[0]/2, size[1]/2), (-size[0]/2, size[1]/2))]
