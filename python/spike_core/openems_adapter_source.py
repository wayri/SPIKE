def point(value):
    if isinstance(value, dict): return float(value.get("x", 0)), float(value.get("y", 0))
    return float(value[0]), float(value[1])

def net_of(value): return str(value.get("net_name") or value.get("net") or "")

def polygon_coordinates(values):
    points = [point(value) for value in values]
    return [[value[0] for value in points], [value[1] for value in points]]

def pin_mesh_lines(grid, direction, values, tolerance=1e-9):
    lines = np.asarray(grid.GetLines(direction, do_sort=True), dtype=float)
    for value in values:
        if not math.isfinite(float(value)) or lines.size == 0: continue
        index = int(np.argmin(np.abs(lines - float(value))))
        if abs(lines[index] - float(value)) <= tolerance:
            lines[index] = float(value)
    grid.SetLines(direction, np.unique(lines).tolist())

def layer_geometry(stackup):
    z = 0.0
    elevations, ranges = {}, []
    for layer in stackup:
        name = str(layer.get("name", ""))
        kind = str(layer.get("type", "unknown")).lower()
        conductor = kind in {"copper", "conductor"} or name.endswith(".Cu")
        dielectric = kind in {"core", "prepreg", "dielectric", "soldermask", "mask"} or "epsilon_r" in layer or "epsilonR" in layer
        if not conductor and not dielectric: continue
        thickness = max(float(layer.get("thickness", layer.get("thickness_mm", 0.035)) or 0.035), 1e-6)
        if conductor:
            elevations[name] = z
        else:
            ranges.append((layer, z - thickness, z))
            z -= thickness
    return elevations, ranges, z

def polygon_for_track(track):
    a, b = point(track.get("start", [0, 0])), point(track.get("end", [0, 0]))
    width = max(float(track.get("width", 0.1) or 0.1), 1e-6)
    dx, dy = b[0] - a[0], b[1] - a[1]
    length = max(math.hypot(dx, dy), 1e-12)
