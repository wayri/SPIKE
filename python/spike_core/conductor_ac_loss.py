"""Internal impedance of a symmetric conducting slab; no external inductance.

Original derivation: magnetic diffusion gives k^2=j*omega*mu*sigma and
z=k*coth(k*t/2)/(2*sigma*w). With u=k*t/2, z=Rdc*u*coth(u).
The declared time convention is exp(+j*omega*time). Equal opposite surface
magnetic fields supply equal current on both broad faces; side edges are absent.

Optional Hammerstad RMS factor: 1+(2/pi)*atan(1.4*(roughness/delta)^2).
Method reference (formula only; independently authored implementation):
https://docs.flexcompute.com/rf/latest/autogenerated/flex_rf/tidy3d/hammerstadsurfaceroughness/
No external source code or fixtures were used. This empirical real-resistance
factor is not a causal broadband phase or complex conductivity model.
"""
from __future__ import annotations

import cmath
import math

MU0 = 4e-7 * math.pi  # Engineering approximation in H/m, consistently used here.


def _finite_number(name: str, value: float, *, allow_zero: bool = False) -> float:
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        raise ValueError(f"{name} must be a finite real SI value.")
    try:
        number = float(value)
    except (ValueError, OverflowError) as exc:
        raise ValueError(f"{name} is outside the representable range.") from exc
    if not math.isfinite(number) or number < 0 or (number == 0 and not allow_zero):
        sign = "nonnegative" if allow_zero else "positive"
        raise ValueError(f"{name} must be finite and {sign}.")
    return number


def _positive_exp(log_value: float, name: str) -> float:
    try:
        value = math.exp(log_value)
    except OverflowError as exc:
        raise ValueError(f"Derived {name} exceeds the representable range.") from exc
    if not math.isfinite(value) or value <= 0:
        raise ValueError(f"Derived {name} is outside the positive representable range.")
    return value


def slab_internal_impedance_per_m(
    *, frequency_hz: float, conductivity_s_per_m: float, width_m: float,
    thickness_m: float, relative_permeability: float = 1.0,
    roughness_rms_m: float = 0.0,
) -> dict:
    """Return scalar-frequency slab impedance and SI diagnostics.

    ``impedance_ohm_per_m`` is a Python complex; the separate real and imaginary
    components are provided for JSON adapters. Skin depth is None at DC.
    Width scales total current in the infinite-width approximation; it does not
    introduce side-edge, proximity, return-path or external inductance physics.
    """
    frequency = _finite_number("frequency_hz", frequency_hz, allow_zero=True)
    sigma = _finite_number("conductivity_s_per_m", conductivity_s_per_m)
    width = _finite_number("width_m", width_m)
    thickness = _finite_number("thickness_m", thickness_m)
    mu_r = _finite_number("relative_permeability", relative_permeability)
    roughness = _finite_number("roughness_rms_m", roughness_rms_m, allow_zero=True)
    log_sigma, log_width, log_thickness = map(math.log, (sigma, width, thickness))
    log_mu = math.log(MU0) + math.log(mu_r)
    log_rdc = -log_sigma - log_width - log_thickness
    rdc = _positive_exp(log_rdc, "DC resistance")
    dc_inductance = _positive_exp(log_mu + log_thickness - math.log(12) - log_width,
                                   "DC internal inductance")
    correction, delta = 1.0, None
    if frequency == 0:
        smooth, regime = complex(rdc, 0), "dc"
    else:
        # a=1/delta=sqrt(pi*f*mu*sigma). Logs prevent intermediate overflow
        # when representable input combinations have very different SI scales.
        log_a = 0.5 * (math.log(math.pi) + math.log(frequency) + log_mu + log_sigma)
        delta = _positive_exp(-log_a, "skin depth")
        log_q = log_a + log_thickness - math.log(2)
        if log_q < math.log(1e-3):
            q = math.exp(log_q)
            # u=(1+j)q: real=1+4q^4/45+O(q^8),
            # imaginary=(2q^2/3)*(1-8q^4/315+O(q^8)).
            real = rdc * (1 + 4 * q**4 / 45)
            log_imag = log_rdc + 2 * log_q + math.log(2 / 3)
            try:
                imag = math.exp(log_imag) * (1 - 8 * q**4 / 315)
            except OverflowError as exc:
                raise ValueError("Derived reactance exceeds the representable range.") from exc
            smooth, regime = complex(real, imag), "dc_series"
        elif log_q >= math.log(20):
            # coth((1+j)q)-1 is bounded by 2/(exp(2q)-1), below
            # 9e-18 at q=20. This avoids overflow from complex hyperbolics.
            surface = _positive_exp(log_a - math.log(2) - log_sigma - log_width,
                                    "high-frequency impedance")
            smooth, regime = complex(surface, surface), "skin_limit"
        else:
            u = complex(1, 1) * math.exp(log_q)
            smooth, regime = rdc * u / cmath.tanh(u), "diffusion"
        if roughness > 0:
            log_argument = math.log(1.4) + 2 * (math.log(roughness) + log_a)
            correction = (2.0 if log_argument > 36 else
                          1 + (2 / math.pi) * math.atan(math.exp(log_argument)))
    impedance = complex(smooth.real * correction, smooth.imag)
    if not all(math.isfinite(v) for v in (impedance.real, impedance.imag)) or impedance.real <= 0 or impedance.imag < 0:
        raise ValueError("Derived impedance is outside the finite passive range.")
    return {
        "impedance_ohm_per_m": impedance,
        "resistance_ohm_per_m": impedance.real,
        "reactance_ohm_per_m": impedance.imag,
        "dc_resistance_ohm_per_m": rdc,
        "dc_internal_inductance_h_per_m": dc_inductance,
        "skin_depth_m": delta, "roughness_correction": correction,
        "regime": regime, "harmonic_convention": "exp(+j*omega*time)",
        "model_status": "approximate",
        "roughness_model": "hammerstad_rms_resistance_only" if roughness else "none",
        "limitations": [
            "Uniform isotropic conductivity and real permeability; isolated symmetric slab with two equally excited broad faces and no side edges.",
            "Internal impedance only: no external inductance, proximity, return geometry, current crowding, or frequency-dependent material dispersion.",
            "Hammerstad RMS correction multiplies only real resistance; it is an empirical magnitude correction, not a causal broadband phase model.",
        ],
    }
